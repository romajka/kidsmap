const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/js/home_map.js', 'utf8');
const start = source.indexOf('  function renderPopupContent(');
const end = source.indexOf('  const CATEGORY_SVGS', start);
const context = {SCRIPT_CONFIG:{routeLabel:"Route"}, window:{kidsMapPhoneButton:()=>''}, escapeHtml:value=>String(value ?? '').replaceAll('<','&lt;'), formatAgeBadge:()=>''};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('  function pointMembers('), source.indexOf('  function businessCount(')) + source.slice(start,end), context);
const point = {name:'First',members:[{id:1,name:'First',url:'/first/',lat:40.4,lng:49.8,translation_fallback:true,content_language:'az',translation_label:'Text in Azerbaijani'},{id:2,name:'Second',url:'/second/'}]};
const html = context.renderPopupContent(point,'Details',{});
assert.ok(html.includes('/first/'), 'first independent business link');
assert.ok(html.includes('/second/'), 'second independent business link');
assert.equal((html.match(/home-map-popup-title-link/g)||[]).length,2);
assert.ok(html.includes('destination=40.4%2C49.8'), 'route includes numeric coordinates');
assert.ok(html.includes('data-translation-fallback') && html.includes('lang="az"'));
assert.ok(!source.includes('function placeMatchesFilters('), 'business filters are server owned');
console.log('Home grouped popup and server filter source boundary PASS');

(async () => {
  const requests = [];
  const applied = [];
  let closed = 0;
  const ctx = {AbortController, fetchFilteredPoints: () => new Promise(resolve => requests.push(resolve))};
  vm.createContext(ctx);
  const a = source.indexOf('  function serverFilterUpdater(');
  const b = source.indexOf('  function interpolateAgeLabel',a);
  vm.runInContext(source.slice(a,b),ctx);
  const update = ctx.serverFilterUpdater(points => applied.push(points), () => closed++, () => {});
  const first = update();
  assert.equal(applied[0]?.length,0,'stale markers removed while filter request pending');
  const second = update();
  requests[1]([{key:'new',members:[{id:2}]}]);
  await second;
  requests[0]([{key:'old',members:[{id:1}]}]);
  await first;
  assert.equal(closed,2,'close stale popup before each filter request');
  assert.equal(applied.filter(points => points.length).length,1,'late response cannot restore stale filtered members');
  assert.equal(applied.at(-1)[0].key,'new');
  console.log('Home stale-response and popup-close PASS');
})().catch(error => { console.error(error); process.exitCode=1; });
