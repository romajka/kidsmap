async page => {
 const base='http://127.0.0.1:8780',checks=[],errors=[],network=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',e=>{if(e.type()==='error')errors.push(e.text());});
 page.on('requestfailed',r=>network.push({url:r.url(),error:r.failure()?.errorText}));
 page.on('response',r=>{if(r.status()>=400)network.push({url:r.url(),status:r.status()});});
 const assert=(v,m)=>{if(!v)throw Error(m);};
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/admin/catalog/organization/');
 await page.locator('.km-admin-header__lang-btn').click();
 await page.locator('form.km-admin-lang-switch-form:has(input[name="language"][value="ru"]) button').first().click();
 await page.waitForLoadState('networkidle');
 await page.screenshot({path:'/mnt/c/kidsmap/output/playwright/manual-check/admin-organizations-after.png'});
 const sortLink=page.locator('#result_list thead a[href*="o="]').last();
 await sortLink.focus();await page.keyboard.press('Enter');await page.waitForLoadState('networkidle');
 const ascending=await page.locator('#result_list th[aria-sort]').getAttribute('aria-sort');
 assert(ascending==='ascending','Ascending sorting state: '+ascending);
 const matrix=await page.locator('#result_list .km-col-arrow--up').evaluate(e=>getComputedStyle(e).transform);
 assert(matrix!=='none','Ascending arrow orientation');
 checks.push({case:'keyboard sort ascending',ariaSort:ascending,transform:matrix});
 await page.locator('#result_list thead a[href*="o="]').last().click();await page.waitForLoadState('networkidle');
 const descending=await page.locator('#result_list th[aria-sort]').getAttribute('aria-sort');
 assert(descending==='descending','Descending state: '+descending);
 checks.push({case:'sort descending',ariaSort:descending});
 await page.goto(base+'/admin/catalog/activity/?q=Baku');await page.waitForLoadState('networkidle');
 const search=await page.locator('#searchbar').inputValue();assert(search==='Baku','Search query lost');
 assert(await page.locator('#result_list tbody tr').count()>0,'Search lost matching rows');
 checks.push({case:'search',value:search,rows:await page.locator('#result_list tbody tr').count()});
 await page.goto(base+'/admin/catalog/organization/?status__exact=published');await page.waitForLoadState('networkidle');
 assert(await page.locator('#result_list tbody tr').count()===1,'Published filter count');
 checks.push({case:'published filter',rows:1});
 await page.goto(base+'/admin/catalog/organization/?q=no-such-admin-repair-place');await page.waitForLoadState('networkidle');
 assert(await page.locator('#result_list tbody tr').count()===0,'Empty search still has rows');
 checks.push({case:'empty search',rows:0});
 await page.goto(base+'/admin/catalog/organization/add/');await page.waitForLoadState('networkidle');
 const addBefore=page.url();
 await page.getByRole('tab',{name:'Контакты',exact:true}).click();
 await page.locator('#id_website').fill('https://invalid');
 await page.locator('button[name="_save_draft"]').click();await page.waitForLoadState('networkidle');
 const validation=await page.locator('.errorlist,.invalid-feedback,.alert-danger,[role="alert"]').allTextContents();
 assert(page.url().split('#')[0]===addBefore.split('#')[0]&&validation.length>0,'Invalid website did not show validation');
 checks.push({case:'invalid website validation',messages:validation});
 const name='QA admin repair '+Date.now();
 await page.getByRole('tab',{name:'Контакты',exact:true}).click();
 await page.locator('#id_website').fill('https://example.invalid/admin-repair');
 await page.getByRole('tab',{name:'Названия',exact:true}).click();
 await page.locator('#id_name_az').fill(name);
 await page.locator('#id_name_ru').fill('Проверка админки 20261004');
 await page.locator('#id_name_en').fill(name);
 await page.locator('button[name="_save_draft"]').click();await page.waitForLoadState('networkidle');
 assert(!page.url().endsWith('/add/'),'Save draft did not redirect');
 await page.goto(base+'/admin/catalog/organization/?q='+encodeURIComponent(name));await page.waitForLoadState('networkidle');
 assert(await page.locator('#result_list tbody tr').count()===1,'Saved organization absent or duplicated');
 const edit=await page.locator('#result_list tbody a[href*="/change/"]').first().getAttribute('href');
 await page.goto(base+edit);await page.waitForLoadState('networkidle');
 await page.getByRole('tab',{name:'Названия',exact:true}).click();
 assert(await page.locator('#id_name_az').inputValue()===name,'Saved organization form not preserved');
 assert(Number(await page.locator('#id_source_version').inputValue())>=1,'Version missing');
 checks.push({case:'draft create and reopen',url:edit,name});
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/admin/catalog/organization/');await page.waitForLoadState('networkidle');
 await page.screenshot({path:'/mnt/c/kidsmap/output/playwright/manual-check/admin-organizations-mobile.png'});
 assert(!errors.length&&!network.length,JSON.stringify({errors,network}));
 return {status:'PASS',checks,errors,network};
}
