const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/js/catalog_map.js','utf8').replace(/  initCatalogMapUi\(\);(?=\s*\}\)\(\);\s*$)/,'  globalThis.api = {renderMapCard, getRouteUrl, hasValidCoordinates};');
const sandbox = {window:{kidsMapPhoneButton:(id)=>`<button data-place="${id}">Call</button>`}};
vm.runInNewContext(source,sandbox);
const labels = {detailsLabel:'Details',routeLabel:'Route',closeLabel:'Close',noRatingLabel:'No rating',noAddressLabel:'No address',noImageLabel:'No image'};
const a={id:1,name:'One <unsafe>',url:'/place/1/',lat:40.42,lng:49.88,price:'25 AZN',translation_fallback:true,content_language:'az',matched_offers:[{name:'English',url:'/activity/1/',groups:[{name:'Young',age:'4–6'}]}]};
const b={id:2,name:'Two',url:'/place/2/',lat:40.42,lng:49.88,price:'90 AZN',has_phone:true,matched_offers:[]};
const html=sandbox.api.renderMapCard({members:[a,b]},labels,false);
assert.ok(html.includes('/place/1/') && html.includes('/place/2/'));
assert.ok(html.includes('One &lt;unsafe&gt;'));
assert.ok(!html.includes('One <unsafe>'));
assert.ok(html.includes('25 AZN') && html.includes('90 AZN') && html.includes('Young · 4–6'));
assert.equal((html.match(/data-map-card-close/g)||[]).length,1);
const filtered=sandbox.api.renderMapCard({members:[a]},labels,true);
assert.ok(!filtered.includes('/place/2/') && !filtered.includes('90 AZN'));
assert.equal(sandbox.api.getRouteUrl({...a,phone:'private',address:'private address'}),'https://www.google.com/maps/dir/?api=1&destination=40.42%2C49.88');
assert.equal(sandbox.api.hasValidCoordinates({lat:NaN,lng:49}),false);
assert.equal(sandbox.api.hasValidCoordinates({lat:null,lng:49}),false);
assert.ok(html.includes('data-translation-fallback') && html.includes('lang="az"'));
assert.equal(sandbox.api.getRouteUrl({lat:NaN,lng:49}), '');
assert.equal(sandbox.api.getRouteUrl({lat:0,lng:0}), '');
console.log('catalog map grouped/filter/escape/route renderer: PASS');
